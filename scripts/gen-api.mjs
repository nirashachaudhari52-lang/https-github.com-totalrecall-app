// Builds functions/_generated/apiRoutes.ts: a static map from "path_METHOD" to each endpoint module,
// so Cloudflare Pages Functions can route /_api/<path> the same way Floot did.
import { readdirSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const epDir = join(root, "endpoints");
const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/_(GET|POST)\.ts$/.test(f)) files.push(p);
  }
})(epDir);

const lines = ["// Generated by scripts/gen-api.mjs — do not edit.", ""];
const entries = [];
files.sort().forEach((p, i) => {
  const rel = relative(epDir, p).replace(/\\/g, "/").replace(/\.ts$/, "");
  const m = rel.match(/^(.*)_(GET|POST)$/);
  lines.push(`import * as m${i} from "../../endpoints/${rel}";`);
  entries.push(`  "${m[1]}_${m[2]}": m${i},`);
});
lines.push("", "export const routes: Record<string, { handle: (r: Request) => Promise<Response> }> = {", ...entries, "};", "");
mkdirSync(join(root, "functions/_generated"), { recursive: true });
writeFileSync(join(root, "functions/_generated/apiRoutes.ts"), lines.join("\n"));
console.log(`gen-api: ${files.length} endpoints`);
